<#
.SYNOPSIS
  Builds a clean, buyer-ready zip of this product from the current
  working tree — no git history, no local dev artifacts, no internal
  tooling files.

.DESCRIPTION
  Copies the project into a temp staging folder while skipping anything
  a buyer shouldn't receive, then compresses that folder into a single
  zip at the project root. Safe to re-run — it always starts from a
  clean staging folder and overwrites the previous zip.

  Excluded (regenerated by the app itself, or dev/internal-only):
    - node_modules, .next, dist, build, .dart_tool, coverage
    - .git, .claude (internal tooling — never part of what's sold)
    - .idea, *.iml, *.tsbuildinfo
    - backend/.env (buyer creates their own from .env.example)
    - backend/uploads/* (recreated automatically on first run)
    - this scripts/ folder itself (release tooling, not part of the product)

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\package-for-sale.ps1
  powershell -ExecutionPolicy Bypass -File scripts\package-for-sale.ps1 -Version 1.1.0
#>

param(
  [string]$Version = "1.0.0"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$productName = "miqat-booking-app"
$stagingDir = Join-Path $root "_package-staging"
$zipName = "$productName-v$Version.zip"
$zipPath = Join-Path $root $zipName

$excludeDirs = @(
  "node_modules", ".next", "dist", "build", ".dart_tool", "coverage",
  ".git", ".claude", ".idea", "_package-staging", "scripts"
)
$excludeFiles = @("*.iml", "*.tsbuildinfo", ".env")

Write-Host "Building $zipName from $root ..."

if (Test-Path $stagingDir) { Remove-Item $stagingDir -Recurse -Force }
New-Item -ItemType Directory -Path $stagingDir | Out-Null

function Copy-Filtered($source, $destination) {
  New-Item -ItemType Directory -Path $destination -Force | Out-Null
  Get-ChildItem -Path $source -Force | ForEach-Object {
    if ($_.PSIsContainer) {
      if ($excludeDirs -contains $_.Name) { return }
      if ($_.FullName -like "*\backend\uploads") { return }
      Copy-Filtered $_.FullName (Join-Path $destination $_.Name)
    } else {
      foreach ($pattern in $excludeFiles) {
        if ($_.Name -like $pattern) { return }
      }
      Copy-Item $_.FullName -Destination $destination
    }
  }
}

Copy-Filtered $root $stagingDir

# The upload endpoint creates this directory itself on first run
# (see backend/src/routes/uploads.ts) — an empty folder just needs to exist.
New-Item -ItemType Directory -Path (Join-Path $stagingDir "backend\uploads") -Force | Out-Null

if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
Compress-Archive -Path "$stagingDir\*" -DestinationPath $zipPath -CompressionLevel Optimal

Remove-Item $stagingDir -Recurse -Force

$sizeMb = [math]::Round((Get-Item $zipPath).Length / 1MB, 1)
Write-Host "Done: $zipPath ($sizeMb MB)"
Write-Host ""
Write-Host "Before uploading, sanity-check the zip:"
Write-Host "  - Extract it somewhere clean and run through docs/README.md's setup from scratch"
Write-Host "  - Confirm .git, .claude, and node_modules are NOT inside"
